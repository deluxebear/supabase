// [self-platform] Phase 2: applies stored settings of an environment-driven
// service (PostgREST, Storage) to a Fleet-managed Compose stack. The settings
// are non-secret, so they travel as a plain Compose override
// (`<domain>/current/compose.yml`); service-config-apply.ts does the rest.
import { toComposeOverrideYaml } from './auth-runtime'
import {
  commitServiceConfigApply,
  loadServiceConfigApplyPlan,
  type ApplyRequest,
  type ServiceConfigApplyAvailability,
  type ServiceConfigApplyOperation,
  type ServiceConfigApplyState,
  type ServiceConfigSpec,
} from './service-config-apply'
import { readStoredServiceConfig, type StoredServiceName } from './service-settings'

const OVERRIDE_PATH = 'compose.yml'

export type EnvServiceApplyStatus = {
  availability: ServiceConfigApplyAvailability
  state: ServiceConfigApplyState
  isOwnedByFleet: boolean
  appliedFields: string[]
  expectedGeneration: number
  operation: ServiceConfigApplyOperation | null
}

export type EnvServiceDefinition = {
  /** Key of platform.service_config. */
  storeKey: StoredServiceName
  spec: ServiceConfigSpec
  render: (stored: Record<string, unknown>) => Record<string, string>
  appliedFields: (stored: Record<string, unknown>) => string[]
}

async function loadPlan(
  definition: EnvServiceDefinition,
  projectRef: string,
  request: ApplyRequest,
  isStrict: boolean
) {
  const stored = await readStoredServiceConfig(projectRef, definition.storeKey)
  const env = definition.render(stored)
  const appliedFields = definition.appliedFields(stored)
  const applyPlan = await loadServiceConfigApplyPlan({
    spec: definition.spec,
    projectRef,
    request,
    isStrict,
    plainFiles: [
      {
        path: OVERRIDE_PATH,
        content: toComposeOverrideYaml(
          definition.spec.service,
          env,
          `# Generated by Fleet from the project ${definition.spec.label}. Do not edit.`
        ),
      },
    ],
    secretsEnv: null,
    hasPlainSettings: appliedFields.length > 0,
  })
  const status: EnvServiceApplyStatus = {
    availability: applyPlan.availability,
    state: applyPlan.state,
    isOwnedByFleet: applyPlan.isOwnedByFleet,
    appliedFields,
    expectedGeneration: applyPlan.expectedGeneration,
    operation: applyPlan.operation,
  }
  return { applyPlan, status }
}

export async function getEnvServiceApplyStatus(
  definition: EnvServiceDefinition,
  projectRef: string,
  request: ApplyRequest
): Promise<EnvServiceApplyStatus> {
  return (await loadPlan(definition, projectRef, request, false)).status
}

export async function applyEnvServiceConfig(
  definition: EnvServiceDefinition,
  input: {
    projectRef: string
    expectedGeneration: number
    confirmOwnership: boolean
    idempotencyKey: string
    actor: string
    correlationId: string
    aal?: string
    aalAuthenticatedAt?: number
  }
) {
  const { applyPlan } = await loadPlan(
    definition,
    input.projectRef,
    { actor: input.actor, correlationId: input.correlationId },
    true
  )
  return commitServiceConfigApply(applyPlan, input)
}
